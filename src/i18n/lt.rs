#[cfg(test)]
mod tests {
    use crate::i18n::Lang;

    #[test]
    fn counts_and_dates_read_naturally() {
        let lt = Lang::parse("lt").unwrap();
        let posts = |n| lt.count(n, "{n} post", "{n} posts");
        assert_eq!(posts(1), "1 įrašas");
        assert_eq!(posts(21), "21 įrašas");
        assert_eq!(posts(11), "Įrašų: 11");
        assert_eq!(posts(5), "Įrašų: 5");
        let date = chrono::NaiveDate::from_ymd_opt(2026, 10, 12).unwrap();
        assert_eq!(lt.date(date), "2026 m. spalio 12 d.");
        assert_eq!(lt.day_month(date), "spalio 12 d.");
    }
}
