#[cfg(test)]
mod tests {
    use crate::i18n::Lang;

    #[test]
    fn counts_and_dates_read_naturally() {
        let de = Lang::parse("de").unwrap();
        assert_eq!(de.count(1, "{n} post", "{n} posts"), "1 Beitrag");
        assert_eq!(de.count(0, "{n} post", "{n} posts"), "0 Beiträge");
        let date = chrono::NaiveDate::from_ymd_opt(2026, 10, 12).unwrap();
        assert_eq!(de.date(date), "12. Okt. 2026");
        assert_eq!(de.day_month(date), "12. Okt.");
    }
}
