#[cfg(test)]
mod tests {
    use crate::i18n::Lang;

    #[test]
    fn counts_and_dates_read_naturally() {
        let fr = Lang::parse("fr").unwrap();
        assert_eq!(fr.count(0, "{n} post", "{n} posts"), "0 article");
        assert_eq!(fr.count(1, "{n} post", "{n} posts"), "1 article");
        assert_eq!(fr.count(2, "{n} post", "{n} posts"), "2 articles");
        let date = chrono::NaiveDate::from_ymd_opt(2026, 10, 12).unwrap();
        assert_eq!(fr.date(date), "12 oct. 2026");
        assert_eq!(fr.day_month(date), "12 oct.");
    }
}
